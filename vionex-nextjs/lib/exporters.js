import { NextResponse } from "next/server";
import ExcelJS from "exceljs";
import PDFDocument from "pdfkit";

/* Turns a list of numbers into a downloadable file: txt, csv, xlsx or pdf. */

const TYPES = {
  txt: "text/plain; charset=utf-8",
  csv: "text/csv; charset=utf-8",
  xlsx: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
  pdf: "application/pdf",
};

export const isExportFormat = (f) => Object.hasOwn(TYPES, f);

async function xlsx(list, title) {
  const wb = new ExcelJS.Workbook();
  wb.creator = "AutoWA";
  const ws = wb.addWorksheet("Numbers");
  ws.columns = [
    { header: "#", key: "i", width: 8 },
    { header: "Phone number", key: "n", width: 20 },
  ];
  ws.getRow(1).font = { bold: true };
  /* numbers are written as TEXT so Excel never shows 9.23E+11 */
  list.forEach((n, i) => ws.addRow({ i: i + 1, n: String(n) }));
  ws.getColumn(2).numFmt = "@";
  ws.views = [{ state: "frozen", ySplit: 1 }];
  if (title) wb.title = title;
  return Buffer.from(await wb.xlsx.writeBuffer());
}

function pdf(list, title) {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: "A4", margin: 40, info: { Title: title || "AutoWA numbers", Author: "AutoWA" } });
    const chunks = [];
    doc.on("data", (c) => chunks.push(c));
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", reject);

    const left = doc.page.margins.left;
    const width = doc.page.width - left - doc.page.margins.right;
    const bottom = doc.page.height - doc.page.margins.bottom;

    doc.font("Helvetica-Bold").fontSize(16).text(title || "Numbers", left, 40, { width });
    doc
      .font("Helvetica")
      .fontSize(9)
      .fillColor("#666666")
      .text(`${list.length.toLocaleString()} numbers · generated by AutoWA on ${new Date().toLocaleString()}`, { width });
    doc.moveDown(0.8).fillColor("#000000").fontSize(10);

    /* four columns of numbers, top to bottom, then the next page */
    const cols = 4;
    const colW = width / cols;
    const lineH = 14;
    let top = doc.y;
    let i = 0;
    while (i < list.length) {
      const rows = Math.max(1, Math.floor((bottom - top) / lineH));
      for (let c = 0; c < cols && i < list.length; c++) {
        for (let r = 0; r < rows && i < list.length; r++, i++) {
          doc.text(`${i + 1}. ${list[i]}`, left + c * colW, top + r * lineH, { width: colW - 6, lineBreak: false });
        }
      }
      if (i < list.length) {
        doc.addPage();
        top = doc.page.margins.top;
      }
    }
    doc.end();
  });
}

/* ---------------------------------------------------------- tables -- */

const csvCell = (v) => {
  const s = String(v ?? "");
  return /[",\r\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
};

async function tableXlsx(columns, rows, title) {
  const wb = new ExcelJS.Workbook();
  wb.creator = "AutoWA";
  const ws = wb.addWorksheet("Report");
  ws.columns = columns.map((c) => ({ header: c.label, key: c.key, width: c.width || 14 }));
  ws.getRow(1).font = { bold: true };
  rows.forEach((r) => ws.addRow(r));
  ws.views = [{ state: "frozen", ySplit: 1 }];
  if (title) wb.title = title;
  return Buffer.from(await wb.xlsx.writeBuffer());
}

function tablePdf(columns, rows, title) {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: "A4", layout: "landscape", margin: 30, info: { Title: title, Author: "AutoWA" } });
    const chunks = [];
    doc.on("data", (c) => chunks.push(c));
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", reject);

    const left = doc.page.margins.left;
    const width = doc.page.width - left - doc.page.margins.right;
    const bottom = doc.page.height - doc.page.margins.bottom;
    const total = columns.reduce((s, c) => s + (c.width || 14), 0);
    const widths = columns.map((c) => ((c.width || 14) / total) * width);
    const rowH = 16;

    doc.font("Helvetica-Bold").fontSize(14).text(title, left, 30);
    doc.font("Helvetica").fontSize(8).fillColor("#666666").text(`${rows.length} rows · generated by AutoWA on ${new Date().toLocaleString()}`);
    let y = doc.y + 8;

    const line = (cells, bold) => {
      doc.font(bold ? "Helvetica-Bold" : "Helvetica").fontSize(7).fillColor("#000000");
      let x = left;
      cells.forEach((v, i) => {
        doc.text(String(v ?? ""), x + 2, y + 4, { width: widths[i] - 4, height: rowH - 4, ellipsis: true, lineBreak: false });
        x += widths[i];
      });
      doc.moveTo(left, y + rowH).lineTo(left + width, y + rowH).strokeColor("#dddddd").lineWidth(0.5).stroke();
      y += rowH;
    };
    const header = () => line(columns.map((c) => c.label), true);

    header();
    for (const r of rows) {
      if (y + rowH > bottom) {
        doc.addPage();
        y = doc.page.margins.top;
        header();
      }
      line(columns.map((c) => r[c.key]));
    }
    doc.end();
  });
}

/* A table (array of row objects) as xlsx / csv / pdf download. */
export async function exportTable(columns, rows, format, baseName, title) {
  let body;
  if (format === "csv") {
    body = [columns.map((c) => csvCell(c.label)).join(","), ...rows.map((r) => columns.map((c) => csvCell(r[c.key])).join(","))].join("\r\n") + "\r\n";
  } else if (format === "xlsx") body = await tableXlsx(columns, rows, title);
  else if (format === "pdf") body = await tablePdf(columns, rows, title);
  else throw new Error("Unsupported report format");

  const safe = String(baseName || "report").replace(/[^\w.-]+/g, "_").slice(0, 100);
  return new NextResponse(body, {
    headers: {
      "Content-Type": TYPES[format],
      "Content-Disposition": `attachment; filename="${safe}.${format}"`,
      "Cache-Control": "no-store",
    },
  });
}

/* Builds the file and returns it as a download response. */
export async function exportResponse(list, format, baseName, title) {
  let body;
  if (format === "txt") body = list.length ? list.join("\r\n") + "\r\n" : "";
  else if (format === "csv") body = "number\r\n" + list.map((n) => `${n}\r\n`).join("");
  else if (format === "xlsx") body = await xlsx(list, title);
  else body = await pdf(list, title);

  const safe = String(baseName || "numbers").replace(/[^\w.-]+/g, "_").slice(0, 100);
  return new NextResponse(body, {
    headers: {
      "Content-Type": TYPES[format],
      "Content-Disposition": `attachment; filename="${safe}.${format}"`,
      "Cache-Control": "no-store",
    },
  });
}
